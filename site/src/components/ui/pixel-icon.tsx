export type PixelIconName = keyof typeof ICONS;
export type PixelBitmap = readonly string[];

interface PixelIconProps {
	name: PixelIconName | PixelBitmap;
	/** When false the pixels are scattered off; when true they assemble. */
	on: boolean;
	/** Bump to replay the assembly (e.g. on hover). */
	replay?: number;
	className?: string;
}

/** A tiny pixel-art icon whose pixels assemble in random order. */
export default function PixelIcon({ name, on, replay = 0, className }: PixelIconProps) {
	const pixels = useMemo(() => (typeof name === 'string' ? ICONS[name] : name).join('').padEnd(81, '.').slice(0, 81).split(''), [name]);
	// New random order for every replay
	const delays = useMemo(
		() => pixels.map(() => Math.random() * 750),
		// eslint-disable-next-line react-hooks/exhaustive-deps
		[pixels, replay]
	);

	return (
		<div aria-hidden="true" className={cn('grid grid-cols-9', className)}>
			{pixels.map((p, i) => (
				<span
					key={`${replay}-${i}`}
					className={cn(
						'aspect-square transition-opacity duration-0',
						p === '#' ? 'bg-current' : 'bg-transparent',
						on ? 'opacity-100' : 'opacity-0'
					)}
					style={{
						transitionDelay: `${delays[i]}ms`,
						animation: on && replay > 0 && p === '#' ? `pixel-in 300ms steps(2) ${delays[i]}ms both` : undefined,
					}}
				/>
			))}
		</div>
	);
}
